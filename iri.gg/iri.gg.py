# mod04: 전적 수정 모듈 (UI 및 mod06_수정 호출) FR-3
# ==============================================================================
def mod04(데이터목록):
    print("\n[전적 수정]")
    찾는날짜 = input("수정할 날짜 입력(YYYY-MM-DD HH:MM): ").strip()

    # 1. mod06을 통해 수정 타겟 조회
    타겟 = mod06_날짜검색(데이터목록, 찾는날짜)

    if 타겟 is None:
        print(">> [EH-02] 데이터 부재 : 데이터가 없다")
        return

    print("선택된 데이터:", 타겟["날짜"], 타겟["이름"], 타겟["무기"])
    print("수정할 항목: 1.등수 2.이름 3.무기 4.딜량 5.킬 6.데스 7.어시")
    선택 = input("선택 (1-7): ").strip()

    항목키 = None
    변경값 = None

    # 2. 입력값 검증 (mod02 사용)
    if 선택 == "1":
        값 = input("새 등수: ").strip()
        if mod02_등수체크(값):
            항목키, 변경값 = "등수", int(값)
        else:
            print(">> [EH-05] 유효 범위 초과 : 잘못된 등수")
            return
    elif 선택 == "2":
        값 = input("새 이름: ").strip()
        if len(값) > 0:
            항목키, 변경값 = "이름", 값
        else:
            print(">> [EH-03] 필수 입력값 누락 : 빈 이름 사용 불가.")
            return
    elif 선택 == "3":
        값 = input("새 무기: ").strip()
        if len(값) > 0:
            항목키, 변경값 = "무기", 값
        else:
            print(">> [EH-03] 필수 입력값 누락 : 빈 무기 사용 불가.")
            return
    elif 선택 in ["4", "5", "6", "7"]:
        필드명_맵 = {"4": ("딜량", "새 딜량"), "5": ("킬", "새 킬"), "6": ("데스", "새 데스"), "7": ("어시", "새 어시")}
        키, 문구 = 필드명_맵[선택]
        값 = input(f"{문구}: ").strip()
        if mod02_숫자체크(값):
            항목키, 변경값 = 키, int(값)
        else:
            print(">> [EH-01] 잘못된 입력 : 숫자로 입력")
            return
    else:
        print(">> [EH-01] 잘못된 입력 : 잘못된 선택")
        return

    # 3. mod06 호출하여 메모리 데이터 수정 (CRUD - Update)
    if mod06_수정(데이터목록, 찾는날짜, 항목키, 변경값):
        # 4. mod07 호출하여 파일 동기화
        if mod07_저장(데이터목록):
            print(">> 수정 및 저장 완료")
        else:
            print(">> 저장 실패")


