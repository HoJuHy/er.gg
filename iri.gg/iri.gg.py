# ==============================================================================
# mod02: 입력값 검사
# ==============================================================================
def mod02_날자체크(날짜글자):
    # 입력된 날짜 문자열의 길이가 정확히 16자인지 확인
    if len(날짜글자) != 16:
        return False
    # 날짜 규격(YYYY-MM-DD HH:MM)에 맞게 각 식별자의 위치가 맞는지 확인
    if 날짜글자[4] != '-' or 날짜글자[7] != '-' or 날짜글자[10] != ' ' or 날짜글자[13] != ':':
        return False
    return True  # 통과


def mod02_등수체크(등수글자):
    # 입력된 등수 문자열이 1 ~ 8 사이에 존재하는지 검사
    return 등수글자 in ["1", "2", "3", "4", "5", "6", "7", "8"]


def mod02_숫자체크(숫자글자):
    # 입력값이 빈 문자열이면 거짓(False)을 반환
    if len(숫자글자) == 0:
        return False
    # 문자열 내부의 모든 글자가 숫자인지 검사
    for 글자 in 숫자글자:
        if 글자 < '0' or 글자 > '9':
            return False
    return True  # 통과


def mod02_공백체크(프롬프트):
    # 공백이 아닌 올바른 문자열을 입력받을 때까지 반복
    while True:
        값 = input(프롬프트).strip()
        if len(값) > 0:
            return 값
        print(">> [EH-03] 필수 입력값 누락 : 글자를 입력.")


def mod02_올바른숫자체크(프롬프트):
    # 올바른 숫자 형태가 입력될 때까지 반복하여 정수로 변환해 반환 (형식 오류는 EH-01 적용)
    while True:
        값 = input(프롬프트).strip()
        if mod02_숫자체크(값):
            return int(값)
        print(">> [EH-01] 잘못된 입력 : 숫자로 입력.")


