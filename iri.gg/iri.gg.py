# mod05: 전적 분석 및 슬라이싱 모듈
# ==============================================================================
def mod05(데이터목록):
    print("\n[전적 분석 및 슬라이싱]")
    print("1. 전체 분석  2. 이름/무기 검색  3. 이름/무기 최근 N판 (슬라이싱)")

    # 저장된 전적 데이터가 전혀 없는 경우 조기 리턴 처리
    if len(데이터목록) == 0:
        print(">> [EH-02] 데이터 부재 : 데이터가 없다.")
        return

    선택 = input("선택 (1-3): ").strip()
    결과목록 = []
    제목 = ""

    # 1번 : 전체 데이터를 대상
    if 선택 == "1":
        결과목록 = 데이터목록
        제목 = "전체 전적"

    # 2번 : 캐릭터명과 무기명이 모두 일치하는 전적을 대상
    elif 선택 == "2":
        찾을이름 = input("캐릭터명: ").strip()
        찾을무기 = input("무기명: ").strip()
        결과목록 = [전적 for 전적 in 데이터목록 if 전적["이름"] == 찾을이름 and 전적["무기"] == 찾을무기]
        제목 = f"{찾을이름} ({찾을무기}) 전체"

    # 3번 : 조건에 일치하는 데이터 중 '최근 N판' 데이터만 음수 슬라이싱([-N:])
    elif 선택 == "3":
        찾을이름 = input("캐릭터명: ").strip()
        찾을무기 = input("무기명: ").strip()
        필터목록 = [전적 for 전적 in 데이터목록 if 전적["이름"] == 찾을이름 and 전적["무기"] == 찾을무기]

        if len(필터목록) == 0:
            print(">> [EH-02] 데이터 부재 : 해당 전적이 없다.")
            return

        몇판글자 = input("최근 몇 판? (N): ").strip()
        if not mod02_숫자체크(몇판글자) or int(몇판글자) <= 0:
            print(">> [EH-01] 잘못된 입력 : 올바른 양의 정수를 입력")
            return
        판수 = int(몇판글자)

        # 리스트의 뒤에서부터 N개의 데이터를 슬라이싱 처리
        결과목록 = 필터목록[-판수:]
        제목 = f"{찾을이름} ({찾을무기}) 최근 {len(결과목록)}판"

    else:
        print(">> [EH-01] 잘못된 입력 : 잘못된 선택")
        return

    # 조건 검색/슬라이싱 결과 데이터가 없는 경우 예외 처리
    if len(결과목록) == 0:
        print(">> [EH-02] 데이터 부재 : 조건에 맞는 데이터가 없음")
        return

    # 검색 및 추출된 데이터 항목들의 총합 계산을 수행
    총판수 = len(결과목록)
    승리수 = sum(1 for 전적 in 결과목록 if 전적["등수"] == 1)  # 1등(승리) 횟수 집계
    등수합 = sum(전적["등수"] for 전적 in 결과목록)
    딜량합 = sum(전적["딜량"] for 전적 in 결과목록)
    킬합 = sum(전적["킬"] for 전적 in 결과목록)
    데스합 = sum(전적["데스"] for 전적 in 결과목록)
    어시합 = sum(전적["어시"] for 전적 in 결과목록)

    # 각종 평균값들을 계산
    승률 = (승리수 / 총판수) * 100.0
    평균등수 = 등수합 / 총판수
    평균딜량 = 딜량합 / 총판수
    평균킬 = 킬합 / 총판수
    평균데스 = 데스합 / 총판수
    평균어시 = 어시합 / 총판수

    # 계산된 평균 통계 지표를 출력 형식에 맞춰 안내
    print("\n------------------------------------------")
    print(f"[{제목}]")
    print(f"총 경기 수: {총판수}판 | 승률: {round(승률, 1)}%")
    print(f"평균 등수: {round(평균등수, 1)}등 | 평균 피해량: {round(평균딜량, 1)}")
    print(f"평균 K/D/A: {round(평균킬, 1)} / {round(평균데스, 1)} / {round(평균어시, 1)}")
    print("------------------------------------------")


