# mod07: 파일 데이터 동기화 (Load & Save)
# ==============================================================================
FILE_PATH = r"C:\python\matches.txt"  # 지정된 파일 경로

def mod07_로드():
    데이터목록 = []
    try:
        with open(FILE_PATH, "r", encoding="utf-8") as 파일:
            for 한줄 in 파일:
                한줄 = 한줄.strip()
                if not 한줄:
                    continue

                조각들 = 한줄.split("|")
                if len(조각들) == 8:
                    데이터목록.append({
                        "날짜": 조각들[0],
                        "등수": int(조각들[1]),
                        "이름": 조각들[2],
                        "무기": 조각들[3],
                        "딜량": int(조각들[4]),
                        "킬": int(조각들[5]),
                        "데스": int(조각들[6]),
                        "어시": int(조각들[7])
                    })
    except Exception:
        pass  # 파일이 없거나 읽기 실패 시 빈 리스트 유지
    return 데이터목록

def mod07_저장(데이터목록):
    try:
        with open(FILE_PATH, "w", encoding="utf-8") as 파일:
            for 전적 in 데이터목록:
                한줄 = f"{전적['날짜']}|{전적['등수']}|{전적['이름']}|{전적['무기']}|{전적['딜량']}|{전적['킬']}|{전적['데스']}|{전적['어시']}\n"
                파일.write(한줄)
        return True
    except Exception:
        return False

