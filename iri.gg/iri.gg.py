def mod06(데이터목록, 찾는날짜):
    # 전달받은 날짜 문자열(식별자)이 기존 데이터목록에 이미 등록되어 있는지 확인
    for 전적 in 데이터목록:
        if 전적["날짜"] == 찾는날짜:
            return True  # 이미 존재하는 날짜인 경우
    return False  # 존재하지 않는 새로운 날짜인 경우


# ==============================================================================
# mod07: 파일 데이터 동기화 (Load & Save)
# ==============================================================================
FILE_PATH = r"C:\python\matches.txt"  # 전적 데이터를 동기화할 TXT 파일의 경로 지정

def mod07_로드():
    # .txt파일에서 데이터를 한 줄씩 읽어와 딕셔너리 리스트 반환
    데이터목록 = []
    try:
        # with open 구문으로 안전하게 파일 읽기 모드(r)로 파일에 접근
        with open(FILE_PATH, "r", encoding="utf-8") as 파일:
            for 한줄 in 파일:
                한줄 = 한줄.strip()
                if not 한줄:
                    continue  # 빈 줄은 건너뜁니다.
                
                # 파이프 '|' 문자를 기준으로 데이터를 구분
                조각들 = 한줄.split("|")
                # 데이터 항목이 정상적으로 8개가 맞는지 확인 후 정수 변환하여 딕셔너리로 구조화
                if len(조각들) == 8:
                    데이터목록.append({
                        "날짜": 조각들[0],
                        "등수": int(조각들[1]),
                        "이름": 조각들[2],
                        "무기": 조각들[3],
                        "딜량": int(조각들[4]),
                        "킬": int(조각들[5]),
                        "데스": int(조각들[6]),
                        "어시": int(조각들[7])
                    })
    except Exception:
        pass  # 파일이 없거나 읽기 실패 시 빈 리스트 유지
    return 데이터목록


def mod07_저장(데이터목록):
    # 메모리에 저장된 전적 데이터목록 전체를 파이프 '|' 기호로 엮어 TXT 파일에 동기화
    try:
        with open(FILE_PATH, "w", encoding="utf-8") as 파일:
            for 전적 in 데이터목록:
                # 각 전적 필드를 파이프 구분자로 합친 하나의 텍스트 줄로 구성
                한줄 = f"{전적['날짜']}|{전적['등수']}|{전적['이름']}|{전적['무기']}|{전적['딜량']}|{전적['킬']}|{전적['데스']}|{전적['어시']}\n"
                파일.write(한줄)  # 파일에 기록
        return True  # 저장 성공
    except Exception:
        return False  # 저장 실패


