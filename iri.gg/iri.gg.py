# mod04: 전적 수정 모듈
# ==============================================================================
def mod04(데이터목록):
    print("\n[전적 수정]")
    찾는날짜 = input("수정할 날짜 입력(YYYY-MM-DD HH:MM): ").strip()

    # 입력받은 날짜와 일치하는 경기 데이터를 탐색
    타겟 = None
    for 전적 in 데이터목록:
        if 전적["날짜"] == 찾는날짜:
            타겟 = 전적
            break

    # 일치하는 날짜의 데이터가 없으면 안내 후 함수를 종료 (EH-02)
    if 타겟 is None:
        print(">> [EH-02] 데이터 부재 : 데이터가 없다")
        return

    # 검색 성공 시 선택된 데이터의 기본 정보와 수정 가능 항목 메뉴를 안내
    print("선택된 데이터:", 타겟["날짜"], 타겟["이름"], 타겟["무기"])
    print("수정할 항목: 1.등수 2.이름 3.무기 4.딜량 5.킬 6.데스 7.어시")
    선택 = input("선택 (1-7): ").strip()

    # 사용자가 선택한 항목만 갱신 처리
    if 선택 == "1":
        값 = input("새 등수: ").strip()
        if mod02_등수체크(값):
            타겟["등수"] = int(값)
        else:
            # 고정범위인 1~8등 오입력에만 EH-05 적용
            print(">> [EH-05] 유효 범위 초과 : 잘못된 등수")
            return
    elif 선택 == "2":
        값 = input("새 이름: ").strip()
        if len(값) > 0:
            타겟["이름"] = 값
        else:
            print(">> [EH-03] 필수 입력값 누락 : 빈 이름 사용 불가.")
            return
    elif 선택 == "3":
        값 = input("새 무기: ").strip()
        if len(값) > 0:
            타겟["무기"] = 값
        else:
            print(">> [EH-03] 필수 입력값 누락 : 빈 무기 사용 불가.")
            return
    elif 선택 in ["4", "5", "6", "7"]:
        # 수치 항목(딜량, 킬, 데스, 어시)에 숫자가 아닌 형태 입력 시 EH-01 적용
        필드명_맵 = {"4": ("딜량", "새 딜량"), "5": ("킬", "새 킬"), "6": ("데스", "새 데스"), "7": ("어시", "새 어시")}
        키, 문구 = 필드명_맵[선택]
        값 = input(f"{문구}: ").strip()
        if mod02_숫자체크(값):
            타겟[키] = int(값)
        else:
            print(">> [EH-01] 잘못된 입력 : 숫자로 입력")
            return
    else:
        print(">> [EH-01] 잘못된 입력 : 잘못된 선택")
        return

    # 수정 후 파일 저장소에 동기화
    if mod07_저장(데이터목록):
        print(">> 수정 및 저장 완료")
    else:
        print(">> 저장 실패")


