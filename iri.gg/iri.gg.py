# mod06: 메모리 내 전적 데이터 리스트 CRUD 및 검색 관리, D가 없네..?
# ==============================================================================
def mod06_등록(데이터목록, 날짜, 등수, 이름, 무기, 딜량, 킬, 데스, 어시):
    # Create 메모리에 새로운 전적 딕셔너리를 생성하고 리스트에 추가
    새전적 = {
        "날짜": 날짜,
        "등수": 등수,
        "이름": 이름,
        "무기": 무기,
        "딜량": 딜량,
        "킬": 킬,
        "데스": 데스,
        "어시": 어시
    }
    데이터목록.append(새전적)
    return 새전적

def mod06_중복체크(데이터목록, 찾는날짜):
    # Read 지정된 날짜(식별자)가 이미 존재하는지 검사
    for 전적 in 데이터목록:
        if 전적["날짜"] == 찾는날짜:
            return True
    return False

def mod06_날짜검색(데이터목록, 찾는날짜):
    # Read 날짜(식별자)에 해당하는 단일 전적 딕셔너리 반환
    for 전적 in 데이터목록:
        if 전적["날짜"] == 찾는날짜:
            return 전적
    return None

def mod06_조건검색(데이터목록, 이름, 무기):
    # Read 캐릭터명과 무기명이 모두 일치하는 전적 목록 반환
    return [전적 for 전적 in 데이터목록 if 전적["이름"] == 이름 and 전적["무기"] == 무기]

def mod06_수정(데이터목록, 찾는날짜, 항목키, 변경값):
    # Update 메모리 내 해당 날짜 데이터의 특정 필드값 수정
    타겟 = mod06_날짜검색(데이터목록, 찾는날짜)
    if 타겟:
        타겟[항목키] = 변경값
        return True
    return False

