# ==============================================================================
# mod02: 입력값 검사 (유효성 검증)
# ==============================================================================
def mod02_날짜체크(날짜글자):
    if len(날짜글자) != 16:
        return False
    if 날짜글자[4] != '-' or 날짜글자[7] != '-' or 날짜글자[10] != ' ' or 날짜글자[13] != ':':
        return False
    return True

def mod02_등수체크(등수글자):
    return 등수글자 in ["1", "2", "3", "4", "5", "6", "7", "8"]

def mod02_숫자체크(숫자글자):
    if len(숫자글자) == 0:
        return False
    for 글자 in 숫자글자:
        if 글자 < '0' or 글자 > '9':
            return False
    return True

def mod02_공백체크(프롬프트):
    while True:
        값 = input(프롬프트).strip()
        if len(값) > 0:
            return 값
        print(">> [EH-03] 필수 입력값 누락 : 글자를 입력하세요.")

def mod02_올바른숫자체크(프롬프트):
    while True:
        값 = input(프롬프트).strip()
        if mod02_숫자체크(값):
            return int(값)
        print(">> [EH-01] 잘못된 입력 : 숫자로 입력하세요.")

# ==============================================================================
# mod03: 전적 등록 모듈 (UI 및 mod06_등록 호출) FR-1
# ==============================================================================
def mod03(데이터목록):
    print("\n[전적 등록]")

    # 1. 날짜 입력 및 중복 체크 (mod02, mod06 사용)
    while True:
        날짜 = input("경기 일시 (YYYY-MM-DD HH:MM): ").strip()
        if not mod02_날짜체크(날짜):
            print(">> [EH-01] 잘못된 입력 : 날짜 형식 오류")
            continue
        if mod06_중복체크(데이터목록, 날짜):
            print(">> [EH-04] 중복된 데이터 등록 : 중복된 날짜 입력")
            return
        break

    # 2. 등수 입력 검사 (mod02 사용)
    while True:
        등수글자 = input("등수 (1~8): ").strip()
        if not mod02_등수체크(등수글자):
            print(">> [EH-05] 유효 범위 초과 : 1~8 숫자로 입력")
            continue
        등수 = int(등수글자)
        break

    # 3. 기타 항목 입력 검증 (mod02 사용)
    이름 = mod02_공백체크("캐릭터명: ")
    무기 = mod02_공백체크("사용 무기: ")
    딜량 = mod02_올바른숫자체크("피해량: ")
    킬 = mod02_올바른숫자체크("킬 수: ")
    데스 = mod02_올바른숫자체크("데스 수: ")
    어시 = mod02_올바른숫자체크("어시스트 수: ")

    # 4. mod06 호출하여 메모리 상에 데이터 추가 (CRUD - Create)
    mod06_등록(데이터목록, 날짜, 등수, 이름, 무기, 딜량, 킬, 데스, 어시)

    # 5. mod07 호출하여 파일 동기화
    if mod07_저장(데이터목록):
        print(">> 저장 완료")
    else:
        print(">> 저장 실패")

