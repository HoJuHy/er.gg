# mod03: 전적 등록 모듈
# ==============================================================================
def mod03(데이터목록):
    print("\n[전적 등록]")

    # 올바른 날짜 양식 및 중복되지 않은 날짜가 입력될 때까지 검사
    while True:
        날짜 = input("경기 일시 (YYYY-MM-DD HH:MM): ").strip()
        if not mod02_날자체크(날짜):
            print(">> [EH-01] 잘못된 입력 : 날짜 형식 오류")
            continue
        # 기존 데이터와 날짜가 중복되면 등록을 중단하고 메인 메뉴로 복귀 (EH-04 식별자 중복)
        if mod06(데이터목록, 날짜):
            print(">> [EH-04] 중복된 데이터 등록 : 중복된 날짜 입력")
            return
        break

    # 1~8 등수 입력 검사 (유효 범위인 1~8등 벗어남 시 EH-05 적용)
    while True:
        등수글자 = input("등수 (1~8): ").strip()
        if not mod02_등수체크(등수글자):
            print(">> [EH-05] 유효 범위 초과 : 1~8 숫자로 입력")
            continue
        등수 = int(등수글자)
        break

    # 캐릭터명, 무기, 딜량, 킬, 데스, 어시스트 수치를 각각 유효성 검사 후 입력
    이름 = mod02_공백체크("캐릭터명: ")
    무기 = mod02_공백체크("사용 무기: ")
    딜량 = mod02_올바른숫자체크("피해량: ")
    킬 = mod02_올바른숫자체크("킬 수: ")
    데스 = mod02_올바른숫자체크("데스 수: ")
    어시 = mod02_올바른숫자체크("어시스트 수: ")

    # 입력받은 개별 데이터들을 딕셔너리로 제작
    새전적 = {
        "날짜": 날짜,
        "등수": 등수,
        "이름": 이름,
        "무기": 무기,
        "딜량": 딜량,
        "킬": 킬,
        "데스": 데스,
        "어시": 어시
    }

    # 데이터목록에 신규 딕셔너리 추가
    데이터목록.append(새전적)

    # 변경된 전체 전적 데이터를 즉시 동기화
    if mod07_저장(데이터목록):
        print(">> 저장 완료")
    else:
        print(">> 저장 실패")


